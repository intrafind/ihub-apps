import { useTranslation } from 'react-i18next';
import { Link } from 'react-router-dom';
import Icon from '../../../shared/components/Icon';
import { MODEL_KNOWLEDGE_SOURCE } from '../../../../../shared/runEvents.js';

/**
 * A status badge: tinted, without an outline, 24px high like the sources
 * entry next to it, which is outlined because it can be clicked (#3521). At
 * least 24px: a long label (a workflow or project name, in a narrow pane)
 * wraps and the badge grows with it instead of spilling out of it.
 */
const BADGE_CLASS =
  'inline-flex items-center gap-1.5 min-h-6 py-0.5 px-2 rounded-full text-xs border border-transparent';

/** A badge's icon and label, in a link or a plain badge. */
function BadgeContent({ icon, label, trailingIcon = null }) {
  return (
    <>
      <Icon name={icon} className="w-3 h-3 shrink-0" />
      <span>{label}</span>
      {trailingIcon && <Icon name={trailingIcon} className="w-3 h-3 shrink-0" />}
    </>
  );
}

/** A badge that only says something: an icon and a label, the details in its tooltip. */
function StatusBadge({ icon, label, tone, title, ...rest }) {
  return (
    <div className={`${BADGE_CLASS} ${tone}`} title={title} {...rest}>
      <BadgeContent icon={icon} label={label} />
    </div>
  );
}

/**
 * Component to display the source of an AI answer (LLM, websearch, sources, workflow, ...).
 * Shows a non-intrusive badge indicating where the information came from.
 *
 * The sources are the ones the server named when the turn ended
 * (`run/ended.knowledgeSources`, or the transcription session's): nothing is
 * inferred here, so an answer without them — a failed turn, one stopped before
 * it wrote anything or cut off by a server restart, a notice, an answer stored
 * before the server kept its sources — shows no badge.
 *
 * @param {Object} props
 * @param {Object} [props.answerSource] - Server-reported answer source (`{ sources }`)
 * @param {Object} [props.workflowResult] - Workflow result metadata when message was produced by a workflow run
 *                                          ({ status, executionId, workflowName })
 */
function AnswerSourceBadge({ answerSource, workflowResult, knowledgeScope = null }) {
  const { t } = useTranslation();
  const scopeBadge = knowledgeScope ? <KnowledgeScopeBadge scope={knowledgeScope} t={t} /> : null;

  // Workflow output takes precedence over other sources: the message was produced
  // by a workflow run, not by the LLM responding from its own knowledge.
  if (workflowResult) {
    const displayName =
      typeof workflowResult.workflowName === 'object'
        ? workflowResult.workflowName.en || Object.values(workflowResult.workflowName)[0]
        : workflowResult.workflowName;
    const label =
      t('chatMessage.answerSource.workflow', 'Generated by workflow') +
      (displayName ? `: ${displayName}` : '');
    const colorClasses = 'bg-cyan-50 text-cyan-700 dark:bg-cyan-900/30 dark:text-cyan-300';

    if (workflowResult.executionId) {
      return (
        <Link
          to={`/workflows/executions/${workflowResult.executionId}`}
          className={`${BADGE_CLASS} hover:underline ${colorClasses}`}
          title={t('chatMessage.answerSource.workflowTooltip', 'Open workflow execution details')}
        >
          <BadgeContent icon="cog" label={label} trailingIcon="external-link" />
        </Link>
      );
    }

    return <StatusBadge icon="cog" label={label} tone={colorClasses} title={label} />;
  }

  const sources = Array.isArray(answerSource?.sources) ? answerSource.sources : [];
  if (sources.length === 0) return scopeBadge;

  // Determine the primary source to display
  let displayText = t('chatMessage.answerSource.mixed');
  let iconName = 'document-text';
  let colorClasses = 'bg-blue-50 text-blue-700 dark:bg-blue-900/30 dark:text-blue-300';

  if (sources.length === 1) {
    const source = sources[0];
    switch (source) {
      case MODEL_KNOWLEDGE_SOURCE:
        // Nothing but the model itself.
        displayText = t('chatMessage.answerSource.llmOnly');
        iconName = 'sparkles';
        colorClasses = 'bg-gray-100 text-gray-600 dark:bg-gray-800/50 dark:text-gray-400';
        break;
      case 'websearch':
        displayText = t('chatMessage.answerSource.websearch');
        iconName = 'globe-alt';
        colorClasses = 'bg-green-50 text-green-700 dark:bg-green-900/30 dark:text-green-300';
        break;
      case 'ifinder':
        displayText = t('chatMessage.answerSource.ifinder');
        iconName = 'document-text';
        colorClasses =
          'bg-emerald-50 text-emerald-700 dark:bg-emerald-900/30 dark:text-emerald-300';
        break;
      case 'sources':
        displayText = t('chatMessage.answerSource.sources');
        iconName = 'document-text';
        colorClasses = 'bg-purple-50 text-purple-700 dark:bg-purple-900/30 dark:text-purple-300';
        break;
      case 'iassistant':
        displayText = t('chatMessage.answerSource.iassistant');
        iconName = 'book-open';
        colorClasses = 'bg-indigo-50 text-indigo-700 dark:bg-indigo-900/30 dark:text-indigo-300';
        break;
      case 'integration':
        // An installed integration, MCP server or remote agent answered the tool calls.
        displayText = t('chatMessage.answerSource.integration');
        iconName = 'link';
        colorClasses = 'bg-sky-50 text-sky-700 dark:bg-sky-900/30 dark:text-sky-300';
        break;
      case 'grounding':
        displayText = t('chatMessage.answerSource.grounding');
        iconName = 'search';
        colorClasses = 'bg-teal-50 text-teal-700 dark:bg-teal-900/30 dark:text-teal-300';
        break;
      case 'email':
        displayText = t('chatMessage.answerSource.email');
        iconName = 'mail';
        colorClasses = 'bg-amber-50 text-amber-700 dark:bg-amber-900/30 dark:text-amber-300';
        break;
      case 'file':
        displayText = t('chatMessage.answerSource.file');
        iconName = 'document-text';
        colorClasses = 'bg-orange-50 text-orange-700 dark:bg-orange-900/30 dark:text-orange-300';
        break;
      case 'audio':
        displayText = t('chatMessage.answerSource.audio');
        iconName = 'microphone';
        colorClasses = 'bg-violet-50 text-violet-700 dark:bg-violet-900/30 dark:text-violet-300';
        break;
      default:
        // Keep default mixed styling
        break;
    }
  } else if (sources.includes('email') && sources.every(s => s === 'email' || s === 'file')) {
    // Email plus its attachments is still the user's own content, not
    // "external" knowledge — keep the email badge rather than the mixed one.
    displayText = t('chatMessage.answerSource.emailWithFiles');
    iconName = 'mail';
    colorClasses = 'bg-amber-50 text-amber-700 dark:bg-amber-900/30 dark:text-amber-300';
  }

  // Create tooltip text listing all sources
  const tooltipText =
    sources.length > 1
      ? `${t('chatMessage.answerSource.tooltip')}\n${sources.map(s => `• ${t(`chatMessage.answerSource.${s}`, s)}`).join('\n')}`
      : displayText;

  return (
    <div className="inline-flex flex-wrap items-center justify-end gap-1.5">
      {scopeBadge}
      <StatusBadge icon={iconName} label={displayText} tone={colorClasses} title={tooltipText} />
    </div>
  );
}

/**
 * How one project of the scope was used, as a short phrase. A searched project
 * the server marked `excerpted` also put the sections that match the question
 * into the prompt: the answer did not rest on search alone.
 */
function scopeModeText(project, t) {
  if (project.mode === 'loaded') return t('chatMessage.knowledgeScope.loadedOne', 'loaded in full');
  if (project.mode === 'searched') {
    return project.excerpted
      ? t('chatMessage.knowledgeScope.searchedExcerptsOne', 'searched, relevant sections loaded')
      : t('chatMessage.knowledgeScope.searchedOne', 'searched');
  }
  return t('chatMessage.knowledgeScope.unavailableOne', 'unavailable');
}

/** A scope entry's name; a project the viewer may not see by name stays anonymous. */
function scopeProjectName(project, t) {
  // An iFinder collection that could not be asked has no name the server remembers.
  if (!project.name && project.id?.startsWith('ifc_')) {
    return t('chatMessage.knowledgeScope.ifinderCollection', 'iFinder collection');
  }
  return (
    project.name || project.id || t('chatMessage.knowledgeScope.privateProject', 'Private project')
  );
}

/** Whether a scope entry is a user project (it has a page to link to). */
const isUserProject = project => typeof project?.id === 'string' && project.id.startsWith('prj_');

/**
 * Which projects the turn reached, and whether each was loaded in full or
 * searched (#1036, `knowledge/scope`), and which it could not reach: a project
 * the user attached whose documents are missing from this answer (an iFinder
 * collection while iFinder is unreachable) gets its own amber notice, so the
 * answer is not mistaken for one that used it.
 */
function KnowledgeScopeBadge({ scope, t }) {
  const all = Array.isArray(scope?.projects) ? scope.projects : [];
  const projects = all.filter(project => project.mode !== 'unavailable');
  const missing = all.filter(project => project.mode === 'unavailable');
  return (
    <>
      {projects.length > 0 && <ReachedScopeBadge projects={projects} t={t} />}
      {missing.length > 0 && <MissingScopeNotice projects={missing} t={t} />}
    </>
  );
}

/**
 * One project is named (and, for a user project, links to its page); several
 * are counted: *3 projects · 2 loaded in full · 1 searched*.
 */
function ReachedScopeBadge({ projects, t }) {
  const loaded = projects.filter(project => project.mode === 'loaded');
  const searched = projects.filter(project => project.mode === 'searched');
  const parts = [];
  if (loaded.length) parts.push(t('chatMessage.knowledgeScope.loaded', { count: loaded.length }));
  if (searched.length)
    parts.push(t('chatMessage.knowledgeScope.searched', { count: searched.length }));
  const single = projects.length === 1 ? projects[0] : null;
  const label = single
    ? `${scopeProjectName(single, t)} · ${scopeModeText(single, t)}`
    : `${t('chatMessage.knowledgeScope.projects', { count: projects.length })} · ${parts.join(' · ')}`;
  const tooltip = projects
    .map(
      project =>
        `${scopeProjectName(project, t)}: ${scopeModeText(project, t)}${
          project.overBudget
            ? ` (${t('chatMessage.knowledgeScope.overBudget', 'over budget')})`
            : ''
        }`
    )
    .join('\n');
  const tone = 'bg-purple-50 text-purple-700 dark:bg-purple-900/30 dark:text-purple-300';
  if (single && isUserProject(single)) {
    return (
      <Link
        to={`/projects/${encodeURIComponent(single.id)}`}
        className={`${BADGE_CLASS} hover:underline ${tone}`}
        title={`${tooltip}\n${t('chatMessage.knowledgeScope.openProject', 'Open the project')}`}
      >
        <BadgeContent icon="folder" label={label} />
      </Link>
    );
  }
  return <StatusBadge icon="folder" label={label} tone={tone} title={tooltip} />;
}

/**
 * The projects the turn was told about and could not read: said once, in amber.
 * The tooltip names them and, for iFinder, says why.
 */
function MissingScopeNotice({ projects, t }) {
  const names = projects.map(project => scopeProjectName(project, t));
  const ifinderDown = projects.some(project => project.reason === 'IFINDER_UNAVAILABLE');
  const label =
    projects.length === 1
      ? t('chatMessage.knowledgeScope.missingOne', '{{name}} · not available', { name: names[0] })
      : t('chatMessage.knowledgeScope.missing', { count: projects.length });
  const why = ifinderDown
    ? t(
        'chatMessage.knowledgeScope.missingIFinder',
        'iFinder could not be reached, so this answer did not use it.'
      )
    : t('chatMessage.knowledgeScope.missingOther', 'This answer did not use it.');
  return (
    <StatusBadge
      role="status"
      icon="exclamation-triangle"
      label={label}
      tone="bg-amber-100 text-amber-800 dark:bg-amber-900/30 dark:text-amber-300"
      title={`${names.join(', ')}: ${why}`}
      data-testid="knowledge-scope-missing"
    />
  );
}

export default AnswerSourceBadge;
